/**
 * 選擇題「正解唯一」出題規則：避免 AI 出出兩個（以上）都對的單選題。
 *
 * 背景：曾出現「下列何者不是網域名稱的一部分？(A) 協定 (B) 類型 (C) 網域 (D) 遞歸查詢」，
 * 預期答案是「遞歸查詢」，但「協定」（https:// 屬於網址 URL，不屬於網域名稱）同樣成立 → 兩個正解。
 * 根因：否定題幹（何者不是／錯誤／非）時，AI 從相鄰概念（URL 組成 vs 網域名稱組成）挑干擾項，
 * 干擾項本身也滿足否定條件；且 prompt 從未要求逐一驗證干擾項。
 *
 * 用法比照 buildCodeSnippetRule()：直接串在各出題 prompt 尾端，所有出題路徑共用同一份文字。
 */

type SingleAnswerRuleOptions = {
  /**
   * 輸出 JSON 中放詳解的欄位名稱；該 prompt 的輸出格式沒有詳解欄位時傳 null，
   * 此時只要求 AI 在內部自我檢查，不會要求多輸出欄位（避免破壞既有 parser）。
   */
  explanationField?: string | null;
};

export function buildSingleAnswerRule({ explanationField = 'explanation' }: SingleAnswerRuleOptions = {}): string {
  const explanationLine = explanationField
    ? `\n- ${explanationField} 欄位除了說明正解，也要簡短說明每個錯誤選項為何錯（例：「(B) 協定屬於網址（URL），不屬於網域名稱」）`
    : '\n- 自我檢查只在內部進行，不要輸出檢查過程，也不要新增任何欄位';

  return `

【選擇題正解唯一規則】
- 單選題必須恰好只有一個可辯護的正確答案；其餘每個干擾項在題幹條件下都必須明確錯誤，不可「也說得通」（多選題同理：每個選項都必須能明確判定對或錯）
- 否定題幹（何者「不是／非／錯誤／不屬於／不正確」）：三個干擾項都必須明確符合題幹的正向條件，只有正解不符合；不可取用相鄰概念當干擾項，因為它們往往也不符合正向條件而變成第二個正解（例：問「網域名稱的組成」卻放入「協定」——協定屬於網址（URL），不屬於網域名稱，也會成為正解）
- 選項用語要精確、不可模稜兩可（例：問網域名稱的組成時，寫「頂級網域（如 .tw）」而非籠統的「網域」）
- 輸出前逐題自我檢查：把每個錯誤選項代入題幹確認它確實錯誤；若有第二個選項也成立，改寫該選項或題幹後再輸出${explanationLine}`;
}
