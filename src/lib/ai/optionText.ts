/**
 * 選項文字處理工具
 *
 * AI 出題時常把選項字母前綴塞進選項文字（例如「(A)電荷耦合元件」），
 * 但本系統的選項是以 {id, text} 儲存、字母由前端／匯出端自行產生，
 * 若文字本身又含「(A)」就會出現「(A) (A)電荷耦合元件」的重覆。
 *
 * 在「AI 回傳 → 存進 DB」的轉存點呼叫 stripOptionLabel()，
 * 即可確保資料庫只存乾淨選項文字（治本）。
 */

/**
 * 去除選項文字開頭已內含的括號字母前綴（如「(A)」「（A）」）。
 * 只剝除「括號＋單一字母」這種 AI 明確輸出的格式，
 * 不會誤傷正常英文選項（例如「A red apple」不含括號，不受影響）。
 */
export function stripOptionLabel(text: string): string {
  return text.replace(/^\s*[（(]\s*[A-Z]\s*[)）]\s*/i, '');
}
